def print_sign(sign):
	for i in range(8):
		for j in range(8):
			if sign[i][j] == 1:
				print("##", end="")
			else:
				print("..", end="")
		print()

def print_mega_sign(sign):
	for i in range(8):
		for j in range(8):
			print(f"{sign[i][j]} ", end="")
		print()

def make_mega_frame(frames):
	out = [[0 for _ in range(8)] for _ in range(8)]

	for frame in frames:
		for r in range(8):
			for c in range(8):
				out[r][c] += frame[r][c]
	return out
	
def ret_predict(indata):
	if indata == 0:
		return "up"
	elif indata == 1:
		return "left"
	elif indata == 2:
		return "right"
	else:
		return "cross"



