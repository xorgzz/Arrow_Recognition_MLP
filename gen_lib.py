import random
import torch


def gen_rand_noise(matrix: list[int], magnitude: float) -> list[int]:
    new_matrix = [row[:] for row in matrix]
    for i in range(8):
        for j in range(8):
            if random.random() > magnitude:
                new_matrix[i][j] ^= 1
    return new_matrix


def shift_matrix(matrix: list[list[int]], dx: int = 0, dy: int = 0) -> list[list[int]]:
    new_matrix = [[0 for _ in range(8)] for _ in range(8)]

    for y in range(8):
        for x in range(8):
            new_x, new_y = x + dx, y + dy
            if 0 <= new_x < 8 and 0 <= new_y < 8:
                new_matrix[new_y][new_x] = matrix[y][x]

    return new_matrix


def is_empty(arr):
    for i in range(8):
        for j in range(8):
            if arr[i][j] == 1:
                return False

    return True


